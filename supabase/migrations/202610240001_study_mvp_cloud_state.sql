BEGIN;

-- Dedicated cloud persistence for the Study MVP.
-- This is separate from the general application snapshot.
CREATE TABLE public.user_study_mvp_state (
  user_id uuid PRIMARY KEY
    REFERENCES auth.users(id) ON DELETE CASCADE,

  state jsonb NOT NULL
    CHECK (
      pg_catalog.jsonb_typeof(state) = 'object'
      AND (state ->> 'schema_version') IS NOT DISTINCT FROM '1'
    ),

  revision bigint NOT NULL DEFAULT 1
    CHECK (revision >= 1),

  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Store prior Study states for recovery.
CREATE TABLE public.user_study_mvp_state_backups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id uuid NOT NULL
    REFERENCES auth.users(id) ON DELETE CASCADE,

  state jsonb NOT NULL
    CHECK (
      pg_catalog.jsonb_typeof(state) = 'object'
      AND (state ->> 'schema_version') IS NOT DISTINCT FROM '1'
    ),

  revision bigint NOT NULL CHECK (revision >= 1),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX user_study_mvp_state_backups_history_idx
  ON public.user_study_mvp_state_backups
    (user_id, created_at DESC, id DESC);

ALTER TABLE public.user_study_mvp_state
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.user_study_mvp_state_backups
  ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can read their own Study MVP state"
  ON public.user_study_mvp_state
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = user_id);

CREATE POLICY "Users can read their own Study MVP backups"
  ON public.user_study_mvp_state_backups
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = user_id);

-- Authenticated clients can read but cannot directly mutate the tables.
-- Writes must go through the revision-checked database function.
REVOKE ALL ON TABLE public.user_study_mvp_state
  FROM PUBLIC, anon, authenticated;

REVOKE ALL ON TABLE public.user_study_mvp_state_backups
  FROM PUBLIC, anon, authenticated;

GRANT SELECT ON TABLE public.user_study_mvp_state
  TO authenticated;

GRANT SELECT ON TABLE public.user_study_mvp_state_backups
  TO authenticated;

-- Validate the state structure and protect append-only historical
-- collections even if a caller bypasses the browser's validation.
CREATE OR REPLACE FUNCTION public.validate_user_study_mvp_state()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
DECLARE
  v_collection text;
  v_old_array jsonb;
  v_new_array jsonb;
  v_old_length integer;
  v_new_length integer;
  v_index integer;
BEGIN
  IF pg_catalog.jsonb_typeof(NEW.state) IS DISTINCT FROM 'object'
     OR (NEW.state ->> 'schema_version') IS DISTINCT FROM '1'
  THEN
    RAISE EXCEPTION 'Invalid Study MVP state or schema version';
  END IF;

  -- These collections are append-only. Existing entries must remain
  -- identical and in their original order.
  FOREACH v_collection IN ARRAY ARRAY[
    'task_events',
    'work_sessions',
    'weekly_metrics',
    'settings_change_history'
  ]
  LOOP
    v_new_array := NEW.state -> v_collection;

    IF pg_catalog.jsonb_typeof(v_new_array)
       IS DISTINCT FROM 'array'
    THEN
      RAISE EXCEPTION
        'Study MVP collection "%" must be an array',
        v_collection;
    END IF;
  END LOOP;

  IF TG_OP = 'INSERT' THEN
    IF NEW.revision <> 1 THEN
      RAISE EXCEPTION 'Initial Study MVP revision must be 1';
    END IF;

    RETURN NEW;
  END IF;

  IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
    RAISE EXCEPTION 'Study MVP owner cannot be changed';
  END IF;

  IF NEW.revision <> OLD.revision + 1 THEN
    RAISE EXCEPTION 'Study MVP revision must advance by exactly one';
  END IF;

  FOREACH v_collection IN ARRAY ARRAY[
    'task_events',
    'work_sessions',
    'weekly_metrics',
    'settings_change_history'
  ]
  LOOP
    v_old_array := COALESCE(
      OLD.state -> v_collection,
      '[]'::jsonb
    );

    v_new_array := NEW.state -> v_collection;

    IF pg_catalog.jsonb_typeof(v_old_array)
       IS DISTINCT FROM 'array'
    THEN
      RAISE EXCEPTION
        'Existing Study MVP collection "%" is invalid',
        v_collection;
    END IF;

    v_old_length := pg_catalog.jsonb_array_length(v_old_array);
    v_new_length := pg_catalog.jsonb_array_length(v_new_array);

    IF v_new_length < v_old_length THEN
      RAISE EXCEPTION
        'Study MVP history "%" cannot shrink',
        v_collection;
    END IF;

    IF v_old_length > 0 THEN
      FOR v_index IN 0..(v_old_length - 1)
      LOOP
        IF (v_old_array -> v_index)
           IS DISTINCT FROM (v_new_array -> v_index)
        THEN
          RAISE EXCEPTION
            'Existing Study MVP history "%" cannot be rewritten or reordered',
            v_collection;
        END IF;
      END LOOP;
    END IF;
  END LOOP;

  RETURN NEW;
END;
$function$;

CREATE TRIGGER user_study_mvp_validate_state_trigger
  BEFORE INSERT OR UPDATE
  ON public.user_study_mvp_state
  FOR EACH ROW
  EXECUTE FUNCTION public.validate_user_study_mvp_state();

-- Preserve previous states on meaningful changes and deletions.
-- Keep the 50 most recent snapshots per user.
CREATE OR REPLACE FUNCTION public.capture_user_study_mvp_state_backup()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_user_id uuid;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF OLD.state IS NOT DISTINCT FROM NEW.state THEN
      RETURN NEW;
    END IF;

    v_user_id := OLD.user_id;

    INSERT INTO public.user_study_mvp_state_backups
      (user_id, state, revision)
    VALUES
      (OLD.user_id, OLD.state, OLD.revision);

  ELSIF TG_OP = 'DELETE' THEN
    v_user_id := OLD.user_id;

    INSERT INTO public.user_study_mvp_state_backups
      (user_id, state, revision)
    VALUES
      (OLD.user_id, OLD.state, OLD.revision);

  ELSE
    RETURN NULL;
  END IF;

  DELETE FROM public.user_study_mvp_state_backups AS b
  WHERE b.user_id = v_user_id
    AND b.id NOT IN (
      SELECT keep.id
      FROM (
        SELECT id
        FROM public.user_study_mvp_state_backups
        WHERE user_id = v_user_id
        ORDER BY created_at DESC, id DESC
        LIMIT 50
      ) AS keep
    );

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$function$;

CREATE TRIGGER user_study_mvp_backup_trigger
  AFTER UPDATE OF state OR DELETE
  ON public.user_study_mvp_state
  FOR EACH ROW
  EXECUTE FUNCTION public.capture_user_study_mvp_state_backup();

-- Require the caller's expected revision. A stale client cannot silently
-- overwrite a state saved by another session or device.
CREATE OR REPLACE FUNCTION public.save_user_study_mvp_state(
  p_state jsonb,
  p_expected_revision bigint
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_user_id uuid;
  v_revision bigint;
BEGIN
  v_user_id := auth.uid();

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication is required'
      USING ERRCODE = '42501';
  END IF;

  IF p_expected_revision IS NULL OR p_expected_revision < 0 THEN
    RAISE EXCEPTION 'Expected revision must be zero or greater'
      USING ERRCODE = '22023';
  END IF;

  IF pg_catalog.jsonb_typeof(p_state) IS DISTINCT FROM 'object'
     OR (p_state ->> 'schema_version') IS DISTINCT FROM '1'
  THEN
    RAISE EXCEPTION 'Invalid Study MVP state or schema version'
      USING ERRCODE = '22023';
  END IF;

  IF p_expected_revision = 0 THEN
    INSERT INTO public.user_study_mvp_state
      (user_id, state, revision, updated_at)
    VALUES
      (v_user_id, p_state, 1, pg_catalog.clock_timestamp())
    ON CONFLICT (user_id) DO NOTHING
    RETURNING revision INTO v_revision;

    IF v_revision IS NULL THEN
      RAISE EXCEPTION
        'Study MVP revision conflict: state already exists; reload before saving'
        USING ERRCODE = '40001';
    END IF;

    RETURN v_revision;
  END IF;

  UPDATE public.user_study_mvp_state
  SET
    state = p_state,
    revision = revision + 1,
    updated_at = pg_catalog.clock_timestamp()
  WHERE user_id = v_user_id
    AND revision = p_expected_revision
  RETURNING revision INTO v_revision;

  IF v_revision IS NULL THEN
    RAISE EXCEPTION
      'Study MVP revision conflict: state changed or no longer exists; reload before saving'
      USING ERRCODE = '40001';
  END IF;

  RETURN v_revision;
END;
$function$;

REVOKE ALL ON FUNCTION public.validate_user_study_mvp_state()
  FROM PUBLIC, anon, authenticated;

REVOKE ALL ON FUNCTION public.capture_user_study_mvp_state_backup()
  FROM PUBLIC, anon, authenticated;

REVOKE ALL ON FUNCTION public.save_user_study_mvp_state(jsonb, bigint)
  FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION
  public.save_user_study_mvp_state(jsonb, bigint)
  TO authenticated;

COMMIT;
